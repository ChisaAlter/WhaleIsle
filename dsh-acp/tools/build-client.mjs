import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(toolsDir, '..');
const runtimeBuildRoot = path.join(packageRoot, 'tools', 'runtime-build');
const outputPath = path.join(packageRoot, 'client', 'client.js');

async function loadEsbuild() {
  try {
    return await import('esbuild');
  } catch {
    const require = createRequire(import.meta.url);
    const nodePath = process.env.NODE_PATH?.split(path.delimiter).filter(Boolean) || [];
    return require(require.resolve('esbuild', { paths: [packageRoot, runtimeBuildRoot, ...nodePath] }));
  }
}

export async function bundleClient() {
  const { build } = await loadEsbuild();
  const result = await build({
    absWorkingDir: packageRoot,
    entryPoints: ['client-src/index.js'],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome100'],
    external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives'],
    write: false,
    legalComments: 'none',
  });
  const bundled = result.outputFiles?.[0]?.text;
  if (!bundled) {
    throw new Error('esbuild did not produce a client bundle for dsh-acp');
  }
  const normalized = bundled.replace(/\r\n/g, '\n');
  return `/* dsh-acp-agents client bundle — generated by node tools/build-client.mjs from client-src/. */
window.__ModuleLoader__.load({
  id: 'dsh-acp-agents',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${normalized}
    return module.exports;
  },
});
`;
}

export async function buildClient() {
  const wrapped = await bundleClient();
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, wrapped, 'utf8');
  return outputPath;
}

export async function checkClient() {
  const expected = await bundleClient();
  let actual;
  try {
    actual = await readFile(outputPath, 'utf8');
  } catch (error) {
    return {
      ok: false,
      reason: `Unable to read ${outputPath}: ${error?.message || String(error)}`,
    };
  }
  const normalizedActual = actual.replace(/\r\n/g, '\n');
  if (normalizedActual === expected) {
    return { ok: true, outputPath };
  }
  const expectedLines = expected.split('\n');
  const actualLines = normalizedActual.split('\n');
  let diffLine = 1;
  const maxLines = Math.max(expectedLines.length, actualLines.length);
  for (let i = 0; i < maxLines; i += 1) {
    if (expectedLines[i] !== actualLines[i]) {
      diffLine = i + 1;
      break;
    }
  }
  return {
    ok: false,
    outputPath,
    diffLine,
    expectedLine: expectedLines[diffLine - 1] ?? '<EOF>',
    actualLine: actualLines[diffLine - 1] ?? '<EOF>',
    reason: `client/client.js is out of sync with client-src/ (first difference at line ${diffLine}). Run \`npm run build:client\`.`,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  if (process.argv.includes('--check')) {
    const status = await checkClient();
    if (!status.ok) {
      console.error(status.reason);
      if (status.diffLine !== undefined) {
        console.error(`  expected: ${status.expectedLine}`);
        console.error(`  actual  : ${status.actualLine}`);
      }
      process.exit(1);
    }
    console.log(`Client bundle is up to date: ${status.outputPath}`);
  } else {
    const written = await buildClient();
    console.log(`Wrote ${written}`);
  }
}
