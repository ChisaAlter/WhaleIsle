import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(toolsDir, '..');
const repoRoot = path.resolve(packageRoot, '..');
const outputPath = path.join(packageRoot, 'client', 'client.js');

async function loadEsbuild() {
  try {
    return await import('esbuild');
  } catch {
    const require = createRequire(import.meta.url);
    const nodePath = process.env.NODE_PATH?.split(path.delimiter).filter(Boolean) || [];
    return require(require.resolve('esbuild', { paths: [packageRoot, repoRoot, ...nodePath] }));
  }
}

export async function buildClient() {
  const { build } = await loadEsbuild();
  const result = await build({
    absWorkingDir: packageRoot,
    entryPoints: ['client-src/index.js'],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome100'],
    external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives'],
    write: false,
    legalComments: 'none',
  });
  const bundled = result.outputFiles?.[0]?.text;
  if (!bundled) {
    throw new Error('esbuild did not produce a client bundle for dsh-acp');
  }
  const normalized = bundled.replace(/\r\n/g, '\n');
  const wrapped = `/* dsh-acp-agents client bundle — generated by node dsh-acp/tools/build-client.mjs from dsh-acp/client-src/. */
window.__ModuleLoader__.load({
  id: 'dsh-acp-agents',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${normalized}
    return module.exports;
  },
});
`;
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, wrapped, 'utf8');
  return outputPath;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const written = await buildClient();
  console.log(`Wrote ${written}`);
}
