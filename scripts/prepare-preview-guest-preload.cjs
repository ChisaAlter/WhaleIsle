const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');

const root = path.join(__dirname, '..');
const output = path.join(root, 'src', 'main', 'preview-guest-preload.bundle.js');

function preparePreviewGuestPreload() {
  // Electron's sandbox preload can require electron, but cannot load local
  // helpers. Bundle the DOM-only dependency closure without widening its API.
  const result = buildSync({
    absWorkingDir: root,
    entryPoints: ['src/main/preview-guest-preload.js'],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    external: ['electron'],
    write: false,
    outfile: output,
    banner: { js: '// Generated by scripts/prepare-preview-guest-preload.cjs.' },
  });
  const content = result.outputFiles[0].text;
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) {
    fs.writeFileSync(output, content);
  }
  return output;
}

module.exports = { preparePreviewGuestPreload };

if (require.main === module) {
  console.log(`[preview] sandbox guest preload ready: ${preparePreviewGuestPreload()}`);
}
