#!/usr/bin/env node
/**
 * Build the vendored `dsh-whale` client bundle from TypeScript/JSX sources
 * (`vendor/dsh-whale/src/client/index.tsx` -> `vendor/dsh-whale/client/client.js`)
 * in DeepSeek Harness `window.__ModuleLoader__.load` factory format.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_PACKAGE_ROOT = path.join(REPO_ROOT, 'vendor', 'dsh-whale');
const LOADER_ID = 'dsh-whale';

/**
 * Shared browser modules seeded by `@deepseek-ai/dsh-client-web/src/platform.ts`.
 * Kept external so the plugin uses the exact React/Harness instances hosted by the shell.
 */
export const HARNESS_CLIENT_EXTERNALS = Object.freeze([
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]);

/**
 * Recursively scan the newest mtime (ms) under a file or directory.
 * @param {string} target
 * @returns {number}
 */
export function newestMtime(target) {
  if (!fs.existsSync(target)) return 0;
  const stat = fs.statSync(target);
  if (!stat.isDirectory()) return stat.mtimeMs;
  let newest = stat.mtimeMs;
  for (const entry of fs.readdirSync(target, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === '.tmp') continue;
    newest = Math.max(newest, newestMtime(path.join(target, entry.name)));
  }
  return newest;
}

/**
 * Whether a rebuild is required given mtimes and `--force`.
 * @param {{ force?: boolean, sourceMtime: number, outputMtime: number }} opts
 * @returns {boolean}
 */
export function shouldBuildDshWhaleClient({ force = false, sourceMtime, outputMtime }) {
  return force || !outputMtime || sourceMtime > outputMtime + 500;
}

/**
 * Verify a generated or prebuilt client bundle registers `id: "dsh-whale"`.
 * @param {string} content
 * @returns {boolean}
 */
export function hasValidLoaderHeader(content) {
  return content.includes('window.__ModuleLoader__.load')
    && (content.includes('id: "dsh-whale"') || content.includes("id: 'dsh-whale'") || content.includes('id:"dsh-whale"'));
}

/**
 * Inline `.css` imports into the single-file plugin bundle by mounting one
 * idempotent `<style data-dsh-whale-style="...">` tag per source module.
 * @param {string} packageRoot
 * @returns {import('esbuild').Plugin}
 */
function inlineCssPlugin(packageRoot) {
  return {
    name: 'dsh-whale-inline-css',
    setup(pluginBuild) {
      pluginBuild.onLoad({ filter: /\.css$/ }, async (args) => {
        const cssText = await fs.promises.readFile(args.path, 'utf8');
        const styleId = path.relative(packageRoot, args.path).split(path.sep).join('/');
        const contents = [
          'if (typeof document !== "undefined") {',
          `  var __id = ${JSON.stringify(styleId)};`,
          '  var __head = document.head;',
          '  var __existing = __head && typeof __head.querySelector === "function" ? __head.querySelector("style[data-dsh-whale-style=" + JSON.stringify(__id) + "]") : null;',
          '  var __style = __existing || (typeof document.createElement === "function" ? document.createElement("style") : null);',
          '  if (__style) {',
          '    if (typeof __style.setAttribute === "function") __style.setAttribute("data-dsh-whale-style", __id);',
          `    __style.textContent = ${JSON.stringify(cssText)};`,
          '    if (!__existing && __head && typeof __head.appendChild === "function") __head.appendChild(__style);',
          '  }',
          '}',
          `export default ${JSON.stringify(cssText)};`,
        ].join('\n');
        return { contents, loader: 'js' };
      });
    },
  };
}

/**
 * Wrap a CJS bundle into Harness `window.__ModuleLoader__.load` format.
 * @param {string} bundledCjs
 * @returns {string}
 */
export function wrapModuleLoaderClient(bundledCjs) {
  return [
    '/* dsh-whale client bundle — generated by scripts/build-dsh-whale-client.mjs */',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(LOADER_ID)},`,
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    var React = require("react");',
    bundledCjs,
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');
}

/**
 * @param {string} output
 * @param {string} content
 */
function writeAtomic(output, content) {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const temp = `${output}.tmp.${process.pid}.${Date.now()}`;
  try {
    fs.writeFileSync(temp, content, 'utf8');
    fs.renameSync(temp, output);
  } catch (error) {
    if (fs.existsSync(temp)) fs.rmSync(temp, { force: true });
    throw error;
  }
}

/**
 * @param {{ packageRoot: string, entry: string, minify: boolean }} opts
 */
async function bundleEntry({ packageRoot, entry, minify }) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120', 'es2022'],
    jsx: 'automatic',
    external: [...HARNESS_CLIENT_EXTERNALS],
    loader: { '.svg': 'text', '.md': 'text', '.txt': 'text' },
    plugins: [inlineCssPlugin(packageRoot)],
    write: false,
    minify,
    legalComments: 'none',
    define: {
      'process.env.NODE_ENV': JSON.stringify(minify ? 'production' : 'development'),
    },
  });
  const bundled = result.outputFiles?.[0]?.text;
  if (!bundled) {
    throw new Error('[dsh-whale] esbuild produced no client bundle output');
  }
  const wrapped = wrapModuleLoaderClient(bundled);
  if (!hasValidLoaderHeader(wrapped)) {
    throw new Error('[dsh-whale] wrapped client bundle failed ModuleLoader header check');
  }
  return wrapped;
}

/**
 * Build `vendor/dsh-whale/src/client/index.tsx` -> `vendor/dsh-whale/client/client.js`.
 * @param {{
 *   packageRoot?: string,
 *   entry?: string,
 *   output?: string,
 *   force?: boolean,
 *   minify?: boolean,
 *   strict?: boolean,
 *   silent?: boolean,
 * }} [options]
 */
export async function buildDshWhaleClient(options = {}) {
  const packageRoot = path.resolve(options.packageRoot || DEFAULT_PACKAGE_ROOT);
  const entry = path.resolve(options.entry || path.join(packageRoot, 'src', 'client', 'index.tsx'));
  const output = path.resolve(options.output || path.join(packageRoot, 'client', 'client.js'));
  /** @type {(msg: string) => void} */
  const log = options.silent ? () => {} : (msg) => console.log(msg);

  if (!fs.existsSync(entry)) {
    if (!options.strict && fs.existsSync(output) && hasValidLoaderHeader(fs.readFileSync(output, 'utf8'))) {
      log('[dsh-whale] src/client/index.tsx not present yet; keeping existing client/client.js');
      return { built: false, skippedMissingEntry: true, entry, output };
    }
    throw new Error(`[dsh-whale] client entry is missing: ${entry}`);
  }

  const sourceMtime = Math.max(
    newestMtime(path.join(packageRoot, 'src')),
    newestMtime(entry),
    newestMtime(path.join(packageRoot, 'package.json')),
  );
  const outputMtime = fs.existsSync(output) ? fs.statSync(output).mtimeMs : 0;
  if (!shouldBuildDshWhaleClient({ force: options.force === true, sourceMtime, outputMtime })) {
    if (hasValidLoaderHeader(fs.readFileSync(output, 'utf8'))) {
      log('[dsh-whale] client bundle is current');
      return { built: false, entry, output };
    }
  }

  const wrapped = await bundleEntry({ packageRoot, entry, minify: options.minify === true });
  writeAtomic(output, wrapped);
  log(`[dsh-whale] built client bundle -> ${path.relative(REPO_ROOT, output) || output}`);
  return { built: true, entry, output, bytes: Buffer.byteLength(wrapped, 'utf8') };
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const args = new Set(process.argv.slice(2));
  buildDshWhaleClient({
    force: args.has('--force'),
    minify: args.has('--minify') || process.env.NODE_ENV === 'production',
    strict: args.has('--strict'),
  }).catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
