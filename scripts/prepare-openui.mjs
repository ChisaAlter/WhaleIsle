/** Build the pinned, complete Open Intelligent UI library into an opaque viewer. */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const upstream = path.join(root, 'vendor/open-intelligent-ui');
const viewer = path.join(root, 'src/openui-viewer');
const resourceFetch = path.join(root, 'src/main/openui-fetch.mjs');
const output = path.join(root, 'src/renderer/openui');
const guideFile = path.join(root, 'vendor/deepseek-harness/packages/client/ui-chat/src/openui-guide.ts');
const require = createRequire(import.meta.url);

function writeChanged(file, value) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === value) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, value);
}

function prepareGuide() {
  const original = fs.readFileSync(path.join(upstream, 'src/generated/system-prompt.txt'), 'utf8').replace(/\r\n?/g, '\n');
  const language = original.replace(/^[^\r\n]+/, 'Inside an openui fenced block, write valid OpenUI Lang only. The following rules apply to that program, not to the surrounding conversation.');
  const guide = [
    '## Interactive answers with Open Intelligent UI',
    'When an interactive explanation, calculator, chart, map, comparison, or working tool helps, put an OpenUI Lang program in a Markdown code fence whose language is openui. It renders and streams directly in the existing conversation. Ordinary prose and normal tool calls remain available outside that fence. Do not wrap ordinary text answers in OpenUI.',
    'Each fence is an independent program. Start the program with root = Col(...). Inputs, @Set, @Reset, and registered functions run locally. @ToAssistant explicitly queues a user message in this same conversation, including current form values. Use local actions for local changes; omit an action only when the Button should ask the assistant.',
    'Get real business data through your existing tools before composing the program. Query has no business-tool provider in this viewer; do not invent live data or use the gallery demo dataset as real results. No filesystem, shell, credentials, or model API is exposed to the generated page. Existing tools and permission requirements still apply.',
    'The complete language and component guide below applies only inside openui fences. Here, Markdown means the registered Markdown component, and answer/page means that fence\'s rendered page. These instructions do not replace the rest of the conversation or its tools.',
    language,
    'End the program with the closing Markdown fence. Continue with ordinary prose only when it adds information the rendered UI does not already show.',
  ].join('\n\n');
  writeChanged(guideFile, '// Generated by scripts/prepare-openui.mjs from the pinned upstream prompt.\nexport const OPENUI_GUIDE = ' + JSON.stringify(guide) + '\n');
}

function newestInput(dir) {
  let newest = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === '.git' || entry.name === '.next') continue;
    const file = path.join(dir, entry.name);
    newest = Math.max(newest, entry.isDirectory() ? newestInput(file) : fs.statSync(file).mtimeMs);
  }
  return newest;
}

function ensureDependencies() {
  const dependency = createRequire(path.join(upstream, 'package.json'));
  try {
    dependency.resolve('@openuidev/react-lang');
    dependency.resolve('maplibre-gl/dist/maplibre-gl-worker.mjs');
    return dependency;
  } catch (error) {
    if (error.code !== 'MODULE_NOT_FOUND') throw error;
  }
  const pnpm = path.join(root, 'node_modules/pnpm/bin/pnpm.mjs');
  const result = spawnSync(process.execPath, [pnpm, 'install', '--dir', upstream, '--lockfile-dir', upstream, '--ignore-workspace', '--frozen-lockfile', '--ignore-scripts', '--no-optional'], {
    cwd: upstream, stdio: 'inherit', windowsHide: true,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`OpenUI dependencies failed to install (${result.status}).`);
  return dependency;
}

export async function prepareOpenUi({ force = false } = {}) {
  prepareGuide();
  const products = ['viewer.html', 'api/wiki.cjs', 'api/image-search.cjs', 'api/street-route.cjs', 'UPSTREAM.md', 'OPENUI-SDK-LICENSES.txt'].map(file => path.join(output, file));
  const inputTime = Math.max(newestInput(path.join(upstream, 'src')), newestInput(viewer),
    fs.statSync(fileURLToPath(import.meta.url)).mtimeMs, fs.statSync(resourceFetch).mtimeMs,
    fs.statSync(path.join(upstream, 'pnpm-lock.yaml')).mtimeMs,
    fs.statSync(path.join(upstream, 'UPSTREAM.md')).mtimeMs);
  if (!force && products.every(file => fs.existsSync(file) && fs.statSync(file).mtimeMs >= inputTime)) return;

  const dependency = ensureDependencies();
  const { build } = require('esbuild');
  const workerFile = dependency.resolve('maplibre-gl/dist/maplibre-gl-worker.mjs');
  const worker = fs.readFileSync(workerFile, 'utf8');
  const result = await build({
    entryPoints: [path.join(viewer, 'index.tsx')],
    absWorkingDir: upstream, outfile: path.join(output, 'viewer.js'),
    bundle: true, write: false, minify: true, format: 'iife', target: 'chrome130', jsx: 'automatic',
    nodePaths: [path.join(upstream, 'node_modules')],
    alias: {
      react: path.join(upstream, 'node_modules/react'),
      'react-dom': path.join(upstream, 'node_modules/react-dom'),
      '@openuidev/lang-core': path.join(viewer, 'runtime-core.ts'),
    },
    define: {
      'process.env.NODE_ENV': '"production"', 'process.env.NEXT_PUBLIC_BASE_PATH': '""',
      'import.meta.url': '"about:srcdoc"', __OPENUI_MAP_WORKER_SOURCE__: JSON.stringify(worker),
    },
    loader: { '.woff2': 'dataurl', '.woff': 'dataurl', '.ttf': 'dataurl', '.svg': 'dataurl', '.png': 'dataurl' },
    logLevel: 'warning',
  });
  const script = result.outputFiles.find(file => file.path.endsWith('.js'))?.text;
  if (!script) throw new Error('OpenUI build produced no viewer script.');
  const style = result.outputFiles.find(file => file.path.endsWith('.css'))?.text ?? '';
  const { createOpenUiDocument } = require(path.join(viewer, 'document.cjs'));
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(products[0], createOpenUiDocument({ script, style }));
  for (const operation of ['wiki', 'image-search', 'street-route']) {
    await build({
      entryPoints: [path.join(upstream, `src/app/api/${operation}/route.ts`)],
      outfile: path.join(output, `api/${operation}.cjs`), bundle: true, platform: 'node', format: 'cjs', target: 'node22', logLevel: 'warning',
      inject: [resourceFetch], external: ['electron'],
    });
  }
  fs.writeFileSync(products[4], fs.readFileSync(path.join(upstream, 'UPSTREAM.md')));
  const sdkLicenses = ['lang-core', 'react-lang', 'react-ui'].map(name => {
    const directory = path.join(upstream, 'node_modules/@openuidev', name);
    const { version } = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
    return `@openuidev/${name} ${version}\n\n${fs.readFileSync(path.join(directory, 'LICENSE'), 'utf8')}`;
  }).join('\n\n---\n\n');
  fs.writeFileSync(products[5], sdkLicenses);
  console.log('[openui] prepared the complete viewer and resource handlers');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--prompt-only')) prepareGuide();
  else await prepareOpenUi({ force: process.argv.includes('--force') });
}
